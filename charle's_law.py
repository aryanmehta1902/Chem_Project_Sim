errors = []

def set_values(target, values, label, skip=()):
    for name, value in values.items():
        if name in skip or not hasattr(target, name):
            continue
        try:
            prop = target.bl_rna.properties.get(name)
            if prop is not None and prop.is_readonly:
                continue
            setattr(target, name, value)
        except (AttributeError, TypeError, ValueError, RuntimeError) as exc:
            errors.append(f'{label}.{name}: {exc}')

def build_nodes(tree, specification):
    tree.nodes.clear()
    nodes = {}
    for item in specification['nodes']:
        node = tree.nodes.new(item['type'])
        node.name = item['name']
        nodes[item['name']] = node
        set_values(node, item['props'], node.name)
        for index, value in item['inputs']:
            if index < len(node.inputs) and hasattr(node.inputs[index], 'default_value'):
                try:
                    node.inputs[index].default_value = value
                except (AttributeError, TypeError, ValueError):
                    pass
    for start_name, start_socket, end_name, end_socket in specification['links']:
        tree.links.new(nodes[start_name].outputs[start_socket],
                       nodes[end_name].inputs[end_socket])

def animate(obj, animation):
    if animation is None:
        return
    for frame, transforms in sorted(animation['frames'].items()):
        for path, vector in transforms.items():
            setattr(obj, path, vector)
            obj.keyframe_insert(data_path=path, frame=int(frame))
    obj.animation_data.action.name = animation['name']
    for curve in obj.animation_data.action.fcurves:
        for key in curve.keyframe_points:
            key.interpolation = 'BEZIER'
            key.handle_left_type = 'AUTO_CLAMPED'
            key.handle_right_type = 'AUTO_CLAMPED'
        curve.update()

def build_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    if scene is None:
        scene = bpy.data.scenes.new(SCENE_NAME)
        bpy.context.window.scene = scene
    scene.name = SCENE_NAME
    collection = bpy.data.collections.new('Collection')
    scene.collection.children.link(collection)

    if WORLD:
        world = bpy.data.worlds.new(WORLD['name'])
        set_values(world, WORLD['props'], 'world', skip=('name', 'use_nodes'))
        world.use_nodes = WORLD['graph'] is not None
        if world.use_nodes:
            build_nodes(world.node_tree, WORLD['graph'])
        scene.world = world

    used_materials = {name for item in OBJECTS for name in item['materials']}
    for item in MATERIALS:
        material = bpy.data.materials.new(item['name'])
        set_values(material, item['props'], item['name'], skip=('name', 'use_nodes'))
        material.use_nodes = item['graph'] is not None
        if material.use_nodes:
            build_nodes(material.node_tree, item['graph'])
        if item['name'] not in used_materials:
            material.use_fake_user = True

    meshes = {}
    for item in OBJECTS:
        kind = item['kind']
        if kind == 'MESH':
            mesh_data = item.get('mesh', meshes.get(item.get('mesh_source')))
            mesh = bpy.data.meshes.new(item['data_name'])
            mesh.from_pydata(mesh_data['vertices'], [], mesh_data['faces'])
            mesh.update()
            for poly, material_index, smooth in zip(mesh.polygons,
                    mesh_data['material_indices'], mesh_data['smooth']):
                poly.material_index = material_index
                poly.use_smooth = smooth
            meshes[item['name']] = mesh_data
            data = mesh
        elif kind == 'FONT':
            data = bpy.data.curves.new(item['data_name'], type='FONT')
            set_values(data, item['font'], item['name'] + '.font')
        elif kind == 'CAMERA':
            data = bpy.data.cameras.new(item['data_name'])
            set_values(data, item['camera'], item['name'] + '.camera')
        elif kind == 'LIGHT':
            data = bpy.data.lights.new(item['data_name'], type=item['light']['type'])
            set_values(data, item['light'], item['name'] + '.light')
        else:
            raise RuntimeError('Unsupported object type: ' + kind)
        obj = bpy.data.objects.new(item['name'], data)
        collection.objects.link(obj)
        obj.location = item['location']
        obj.rotation_euler = item['rotation']
        obj.scale = item['scale']
        obj.display_type = item['display_type']
        obj.hide_render = item['hide_render']
        obj.hide_viewport = item['hide_viewport']
        for material_name in item['materials']:
            data.materials.append(bpy.data.materials[material_name])
        animate(obj, item['animation'])

    for item in OBJECTS:
        obj = bpy.data.objects[item['name']]
        for mod_info in item['modifiers']:
            modifier = obj.modifiers.new(mod_info['name'], mod_info['type'])
            if mod_info['type'] == 'FLUID':
                modifier.fluid_type = mod_info['fluid_type']
                if modifier.fluid_type == 'DOMAIN':
                    settings = modifier.domain_settings
                    settings.domain_type = mod_info['settings']['domain_type']
                    set_values(settings, mod_info['settings'], item['name'] + '.domain',
                               skip=('domain_type',))
                    for name in ('use_spray_particles', 'use_bubble_particles',
                                 'use_foam_particles', 'use_tracer_particles'):
                        if name in mod_info['settings']:
                            setattr(settings, name, mod_info['settings'][name])
                elif modifier.fluid_type == 'FLOW':
                    set_values(modifier.flow_settings, mod_info['settings'],
                               item['name'] + '.flow')
            else:
                set_values(modifier, mod_info['settings'], item['name'] + '.modifier')

    scene.camera = bpy.data.objects['Camera']
    scene.frame_start = FIRST_FRAME
    scene.frame_end = LAST_FRAME
    set_values(scene, SCENE_SETTINGS, 'scene')
    set_values(scene.render, RENDER_SETTINGS, 'render', skip=('engine', 'filepath'))
    scene.render.engine = RENDER_SETTINGS['engine']
    scene.render.filepath = '//chemistry_project_part_3_render'
    set_values(scene.render.image_settings, IMAGE_SETTINGS, 'image')
    set_values(scene.render.ffmpeg, MOVIE_SETTINGS, 'movie')
    set_values(scene.cycles, CYCLES_SETTINGS, 'cycles', skip=('name',))
    set_values(scene.view_settings, COLOR_SETTINGS, 'color',
               skip=('white_balance_whitepoint',))
    set_values(scene.display_settings, DISPLAY_SETTINGS, 'display')
    scene.frame_set(FIRST_FRAME)
    domain = bpy.data.objects['Smoke Domain']
    domain.select_set(True)
    bpy.context.view_layer.objects.active = domain

    for error in errors:
        print(error)
    print('Chemistry project part 3 built. Save the file, then bake both domains.')

    if BAKE_SIMULATIONS_NOW:
        for name in ('Smoke Domain', 'Smoke Domain.001'):
            bpy.ops.object.select_all(action='DESELECT')
            domain = bpy.data.objects[name]
            domain.select_set(True)
            bpy.context.view_layer.objects.active = domain
            bpy.ops.fluid.bake_all()

build_scene()
