issues = []

def set_properties(target, values, label, exclude=()):
    for name, value in values.items():
        if name in exclude or not hasattr(target, name):
            continue
        try:
            prop = target.bl_rna.properties.get(name)
            if prop is not None and prop.is_readonly:
                continue
            setattr(target, name, value)
        except (AttributeError, TypeError, ValueError, RuntimeError) as ex:
            issues.append(f'{label}.{name}: {ex}')

def make_nodes(tree, spec):
    tree.nodes.clear()
    made = {}
    for ns in spec['nodes']:
        n = tree.nodes.new(ns['type'])
        n.name = ns['name']
        made[n.name] = n
        for socket_name, value in ns.get('inputs', {}).items():
            socket = n.inputs.get(socket_name)
            if socket is not None and hasattr(socket, 'default_value'):
                try:
                    socket.default_value = value
                except (TypeError, ValueError, AttributeError):
                    pass
    for from_node, from_socket, to_node, to_socket in spec['links']:
        try:
            tree.links.new(made[from_node].outputs[from_socket],
                           made[to_node].inputs[to_socket])
        except (KeyError, TypeError) as ex:
            issues.append(f'node link {from_node} -> {to_node}: {ex}')

def add_animation(obj, od):
    if not od['animation']:
        return
    for frame, transforms in sorted(od['animation_frames'].items()):
        for path, vector in transforms.items():
            setattr(obj, path, vector)
            obj.keyframe_insert(data_path=path, frame=int(frame))
    action = obj.animation_data.action
    action.name = od['animation']
    for curve in action.fcurves:
        for key in curve.keyframe_points:
            key.interpolation = 'BEZIER'
            key.handle_left_type = 'AUTO_CLAMPED'
            key.handle_right_type = 'AUTO_CLAMPED'
        curve.update()

def rebuild():

    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    if scene is None:
        scene = bpy.data.scenes.new(SCENE_NAME)
        bpy.context.window.scene = scene
    scene.name = SCENE_NAME
    collection = bpy.data.collections.new('Collection')
    scene.collection.children.link(collection)

    for ws in WORLDS:
        world = bpy.data.worlds.new(ws['name'])
        set_properties(world, ws['properties'], world.name,
                       exclude=('name', 'use_nodes'))
        world.use_nodes = bool(ws['nodes'])
        if world.use_nodes:
            make_nodes(world.node_tree, ws)
        scene.world = world
    for ms in MATERIALS:
        mat = bpy.data.materials.new(ms['name'])
        set_properties(mat, ms['properties'], mat.name,
                       exclude=('name', 'use_nodes'))
        mat.use_nodes = bool(ms['nodes'])
        if mat.use_nodes:
            make_nodes(mat.node_tree, ms)
        if ms['name'] == 'Dots Stroke':

            mat.use_fake_user = True

    panel_mesh = next(o['mesh'] for o in OBJECTS
                      if o['name'] == 'Cube')
    for od in OBJECTS:
        kind = od['type']
        if kind == 'MESH':
            mesh_data = od.get('mesh', panel_mesh)
            mesh = bpy.data.meshes.new(od['data'])
            mesh.from_pydata(mesh_data['coordinates'], [], mesh_data['faces'])
            mesh.update()
            for poly, index, smooth in zip(mesh.polygons,
                    mesh_data['face_materials'], mesh_data['smooth']):
                poly.material_index = index
                poly.use_smooth = smooth
            datablock = mesh
        elif kind == 'FONT':
            datablock = bpy.data.curves.new(od['data'], type='FONT')
            set_properties(datablock, od['font'], od['name'] + '.font',
                exclude=('name', 'font', 'font_bold', 'font_italic',
                         'font_bold_italic', 'texspace_location', 'texspace_size'))
        elif kind == 'CAMERA':
            datablock = bpy.data.cameras.new(od['data'])
            set_properties(datablock, od['camera'], od['name'] + '.camera',
                exclude=('name', 'angle', 'angle_x', 'angle_y'))
        elif kind == 'LIGHT':
            datablock = bpy.data.lights.new(od['data'], type=od['light']['type'])
            set_properties(datablock, od['light'], od['name'] + '.light',
                           exclude=('name',))
        else:
            raise RuntimeError('Unsupported object type ' + kind)
        obj = bpy.data.objects.new(od['name'], datablock)
        collection.objects.link(obj)
        obj.location = od['location']
        obj.rotation_euler = od['rotation_euler']
        obj.scale = od['scale']
        obj.hide_render = od['hide_render']
        obj.hide_viewport = od['hide_viewport']
        set_properties(obj, od['object_properties'], od['name'],
                       exclude=('hide_render', 'hide_viewport'))
        for material_name in od['materials']:
            if material_name:
                datablock.materials.append(bpy.data.materials[material_name])
        add_animation(obj, od)

    emitter = bpy.data.objects['Icosphere']
    flow_mod = emitter.modifiers.new('Fluid', 'FLUID')
    flow_mod.fluid_type = 'FLOW'
    set_properties(flow_mod.flow_settings, FLOW_SETTINGS, 'smoke flow')

    domain_obj = bpy.data.objects['Smoke Domain']
    domain_mod = domain_obj.modifiers.new('Fluid', 'FLUID')
    domain_mod.fluid_type = 'DOMAIN'
    domain_mod.domain_settings.domain_type = 'GAS'
    set_properties(domain_mod.domain_settings, DOMAIN_SETTINGS, 'smoke domain',
                   exclude=('domain_type',))

    for key in ('use_spray_particles', 'use_bubble_particles',
                'use_foam_particles', 'use_tracer_particles'):
        setattr(domain_mod.domain_settings, key, DOMAIN_SETTINGS[key])

    scene.camera = bpy.data.objects['Camera']
    scene.frame_start = FIRST_FRAME
    scene.frame_end = LAST_FRAME
    set_properties(scene, SCENE_SETTINGS, 'scene')
    set_properties(scene.render, RENDER_SETTINGS, 'render',
                   exclude=('filepath', 'engine'))
    scene.render.engine = RENDER_SETTINGS['engine']
    scene.render.filepath = '//chemistry_project_render'
    set_properties(scene.render.image_settings,
                   IMAGE_SETTINGS, 'image output')
    set_properties(scene.render.ffmpeg, MOVIE_SETTINGS, 'ffmpeg')
    set_properties(scene.cycles, CYCLES_SETTINGS, 'cycles',
                   exclude=('name',))
    set_properties(scene.view_settings, COLOR_SETTINGS,
                   'color management', exclude=('white_balance_whitepoint',))
    set_properties(scene.display_settings, DISPLAY_SETTINGS,
                   'display settings')
    scene.use_nodes = COMPOSITOR['use_nodes']
    if scene.use_nodes:
        make_nodes(scene.node_tree, COMPOSITOR)
    scene.frame_set(1)
    bpy.context.view_layer.objects.active = domain_obj
    domain_obj.select_set(True)
    if issues:
        print('Noncritical property differences in this Blender version:')
        for issue in issues:
            print('  ' + issue)
    print('Chemistry project built. Save the .blend, then bake the smoke.')

    if BAKE_SMOKE_NOW:
        bpy.ops.fluid.bake_all()

rebuild()
